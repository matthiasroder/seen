import {copyFile, readFile, writeFile} from 'node:fs/promises';
// Byte-identical shared capture and queue logic; the mobile transport is separate.
for (const name of ['capture.js', 'store.js', 'core.js', 'icon-128.png']) {
  await copyFile(new URL('../extension/' + name, import.meta.url), new URL('../mobile/extension/' + name, import.meta.url));
}
const paths = ['../extension/core.js', '../extension/store.js', '../mobile/background-source.mjs'];
const code = await Promise.all(paths.map(async path => (await readFile(new URL(path, import.meta.url), 'utf8')).replace(/^import .*;\n/gm, '').replace(/^export /gm, '')));
await writeFile(new URL('../mobile/extension/background.js', import.meta.url), '// Generated by scripts/mobile-resources.mjs.\n' + code.join('\n'));
